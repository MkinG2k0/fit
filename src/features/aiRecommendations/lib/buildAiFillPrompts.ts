import { AI_FILL_HISTORY_MONTHS } from "../model/aiFillConstants";

export const getAiFillSystemPrompt = (): string => {
  return [
    "Ты — тренер по силовым тренировкам. Отвечай строго по фактам, без подбадриваний и воды.",
    "Задача: предложить ДОПОЛНИТЕЛЬНЫЕ подходы (вес и повторы) к уже сделанным сегодня — только то, что ещё стоит сделать.",
    "Не повторяй подходы, которые пользователь уже выполнил в текущей сессии.",
    "Порядок sets — как в зале: от разминки/лёгкого к рабочему (не от тяжёлого к лёгкому).",
    "Не ставь диагнозов, не лечи травмы, не давай медицинских назначений.",
    "Выход СТРОГО одним JSON-объектом без markdown, без пояснений и без текста вокруг:",
    '{"sets":[{"weight":number,"reps":number},...]}',
    "Если уже достаточно объёма — верни {\"sets\":[]} или минимум 1–2 добивающих подхода по данным.",
  ].join(" ");
};

export const buildAiFillUserPrompt = (
  exerciseName: string,
  workoutLogText: string,
  alreadyDoneTodayText: string,
  months: number = AI_FILL_HISTORY_MONTHS,
): string => {
  const alreadyDoneBlock = alreadyDoneTodayText.trim()
    ? [
        "Уже сделано СЕГОДНЯ в этой сессии (эти подходы НЕ дублируй):",
        alreadyDoneTodayText.trim(),
        "",
        "Предложи только оставшиеся подходы — сколько ещё сделать после уже выполненного.",
      ].join("\n")
    : [
        "В текущей сессии пока нет залогированных подходов.",
        "Предложи полную сессию для этого упражнения (разминка → рабочие).",
      ].join("\n");

  const historyBlock = workoutLogText.trim()
    ? [
        `История за последние ${months} мес. (только это упражнение, для контекста прогрессии):`,
        "",
        workoutLogText.trim(),
      ].join("\n")
    : `Истории за последние ${months} мес. нет — опирайся на уже сделанное сегодня, если есть.`;

  return [
    `Упражнение: ${exerciseName}.`,
    "",
    alreadyDoneBlock,
    "",
    historyBlock,
    "",
    "Верни разумное число ДОПОЛНИТЕЛЬНЫХ подходов (обычно 1–4). Порядок: лёгкие/разминка раньше тяжёлых рабочих.",
    "Не выдумывай другие упражнения. Вес и повторы — числа.",
    'Верни только JSON: {"sets":[{"weight":number,"reps":number},...]}.',
  ].join("\n");
};
